"""THREE_D_AGENT — 3D scene planning and Blender script generation.

This is the agent the router selects for 3D/Blender requests. Blender itself is a
TOOL (BLENDER_TOOL) that this agent owns — the router never touches Blender.

    THREE_D_AGENT -> model -> bpy script -> syntax check -> BLENDER_TOOL -> scene or an honest failure

A scene is reported only when BLENDER_TOOL actually runs Blender and writes one.
"""

import re
from contextvars import ContextVar

from agents.base_agent import BaseAgent
from errors import AgentExecutionError
from models import get_fallbacks, get_model, get_provider

ROLE = "three_d"

# Per chat request. Unset means the existing tool path, so callers that do not
# send the plugin toggle keep the current Blender behavior.
blender_capability: ContextVar[bool] = ContextVar("blender_capability", default=True)

SYSTEM = (
    "You are the 3D Agent.\n"
    "Focus on 3D design, Blender workflows, scene planning, geometry, materials, "
    "and Blender Python generation.\n"
    "When asked to create or change a scene, return one executable Blender Python "
    "script that uses bpy. The script must be valid Python and runnable as-is.\n"
    "Do not wrap the script in markdown fences. Do not mix explanatory text into "
    "the executable script.\n"
    "The script must create every object that should exist in the scene after this "
    "request. On a follow-up, modify, or extend, preserve the existing scene: "
    "return the full script, including every object that should remain, not only "
    "the new object.\n"
    "This Blender build's Principled BSDF node has no input named Specular or "
    "Transmission. Use Specular IOR Level and Transmission Weight.\n"
    "Do not call bpy.ops.wm.redraw_timer. Background execution has no window.\n"
    "Do not claim the script has already been executed. BLENDER_TOOL reports that."
)

_FENCE = re.compile(r"```(?:python|py)?[ \t]*\n(.*?)```", re.DOTALL)

_SCRIPT_HEADER = '''"""Auto-generated by AgentRoute :: THREE_D_AGENT (offline template fallback).

Deterministic starter scene used when no model response is available.
Run inside Blender:  blender --background --python this_script.py
"""'''


class ThreeDAgent(BaseAgent):
    name = "THREE_D_AGENT"
    description = "3D design & Blender workflows"
    capabilities = (
        "3d_design",
        "scene_generation",
        "blender",
        "object_generation",
        "material_planning",
        "geometry_planning",
    )
    available_tools = ("BLENDER_TOOL",)
    system_prompt = SYSTEM

    def __init__(self):
        self.model_provider = get_provider(ROLE)
        self.model_id = get_model(ROLE)
        self.fallback_model_ids = tuple(get_fallbacks(ROLE))

    # --- main flow ----------------------------------------------------------
    def run(self, prompt: str) -> str:
        """Ask the model for a scene script, then hand a valid script to BLENDER_TOOL."""
        text = self.generate_script(prompt)
        script, error = _validated_bpy_script(text)
        if script is None and error is None:
            return text
        if error:
            retried = self.regenerate_script(prompt, script or "", error)
            if retried:
                text = retried
                script, error = _validated_bpy_script(text)
            if error or not script:
                return syntax_failure(error or "The regenerated reply did not contain a bpy script.")
        if not blender_capability.get():
            return capability_blocked(text)
        tool = self.get_tool("BLENDER_TOOL")
        result = tool.execute(script)
        if result.metadata.get("executed") and not result.success:
            retried = self.regenerate_after_execution(prompt, script, result.error or "")
            if retried:
                script2, error2 = _validated_bpy_script(retried)
                if script2 and not error2:
                    text = retried
                    result = tool.execute(script2)
        return compose_tool_response(text, result)

    def regenerate_script(self, prompt: str, script: str, error: str) -> str:
        """Ask the same model once more for a valid script for this same request."""
        follow_up = (
            f"{(prompt or '').rstrip()}\n\n"
            "The Blender script below was not executed because it is not valid Python.\n"
            f"Syntax error: {error}\n"
            "Write the script again for the same request. "
            "Return one complete executable bpy script with valid Python syntax. "
            "Do not wrap it in markdown fences. Do not add explanatory text. "
            "Preserve every object that should remain in the scene.\n\n"
            f"{script}"
        )
        try:
            text = self._complete(follow_up, system=self.system_prompt)
        except AgentExecutionError:
            return ""
        return text.strip()

    def regenerate_after_execution(self, prompt: str, script: str, error: str) -> str:
        """Ask once more after Blender ran the script and did not write a scene."""
        detail = (error or "Blender did not write a scene file.").strip()
        if len(detail) > 2000:
            detail = detail[-2000:]
        follow_up = (
            f"{(prompt or '').rstrip()}\n\n"
            "The Blender script below was executed and failed. No scene file was written.\n"
            f"Blender error:\n{detail}\n"
            "Write the script again for the same request. "
            "Return one complete executable bpy script with valid Python syntax. "
            "Do not wrap it in markdown fences. Do not add explanatory text. "
            "Preserve every object that should remain in the scene.\n\n"
            f"{script}"
        )
        try:
            text = self._complete(follow_up, system=self.system_prompt)
        except AgentExecutionError:
            return ""
        return text.strip()

    def generate_script(self, prompt: str) -> str:
        """Ask the model; fall back to a deterministic template if it fails."""
        try:
            text = self._complete(prompt, system=self.system_prompt)
        except AgentExecutionError:
            return self.build_blender_script(prompt)
        return text.strip() or self.build_blender_script(prompt)

    # --- tool path (available, never automatic) -----------------------------
    def validate_script(self, script: str):
        """Hand a script to BLENDER_TOOL.

        Execution remains gated by BLENDER_EXECUTION_ENABLED (default false), so
        this validates only. Nothing in Step 5 calls this automatically.
        """
        return self.get_tool("BLENDER_TOOL").run(script)

    def build_blender_script(self, prompt: str) -> str:
        """Deterministic, offline, valid bpy starter script (no model required)."""
        safe_prompt = prompt.replace('"""', "'''").strip()
        return f'''{_SCRIPT_HEADER}

import bpy

# --- Request spec -----------------------------------------------------------
# User request: {safe_prompt!r}
# Placeholder geometry - refine to match the request.

def clear_scene():
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)

def build():
    clear_scene()

    bpy.ops.mesh.primitive_cube_add(size=2.0, location=(0.0, 0.0, 1.0))
    obj = bpy.context.active_object
    obj.name = "AgentRoute_Placeholder"

    mat = bpy.data.materials.new(name="AgentRoute_Material")
    mat.use_nodes = True
    obj.data.materials.append(mat)

    bpy.ops.mesh.primitive_plane_add(size=20.0, location=(0.0, 0.0, 0.0))
    return obj

if __name__ == "__main__":
    build()
'''


def python_syntax_error(script: str) -> str | None:
    """A compile error, or None when the script is valid Python."""
    try:
        compile(script, "<blender_script>", "exec")
    except SyntaxError as exc:
        detail = exc.msg or "invalid syntax"
        line = exc.lineno or 0
        source = (exc.text or "").strip()
        if source:
            return f"{detail} (line {line}): {source}"
        return f"{detail} (line {line})"
    return None


def _validated_bpy_script(text: str) -> tuple[str | None, str | None]:
    """The extracted bpy script and its syntax error, if it has one."""
    script = extract_bpy_script(text)
    if not script:
        return None, None
    return script, python_syntax_error(script)


def capability_blocked(model_text: str) -> str:
    """Honest report used when the Blender plugin is off. Blender is not launched."""
    return "\n".join(
        [
            (model_text or "").rstrip(),
            "",
            "Blender is disabled. Enable the Blender plugin to execute this 3D task.",
            "Blender tool result:",
            "- tool: BLENDER_TOOL",
            "- invoked: no",
            "- executed: no",
            "- success: no",
            "- note: No Blender scene was created.",
        ]
    ).strip()


def syntax_failure(error: str) -> str:
    """Honest report used when Blender was not launched."""
    return (
        "Blender was not launched because the script is not valid Python. "
        "No scene was created.\n"
        f"- syntax error: {error}"
    )


def extract_bpy_script(text: str) -> str | None:
    """The bpy script inside a model reply, when one is present."""
    for block in _FENCE.findall(text or ""):
        if "bpy" in block:
            return block.strip()
    body = (text or "").strip()
    if "import bpy" in body or "bpy." in body:
        return body
    return None


def compose_tool_response(model_text: str, result) -> str:
    """Model text plus the tool's actual outcome. Never claims a scene that was not written."""
    executed = bool(result.metadata.get("executed"))
    created = executed and result.success and bool(result.artifacts)
    lines = [
        (model_text or "").rstrip(),
        "",
        "Blender tool result:",
        f"- tool: {result.tool}",
        "- invoked: yes",
        f"- executed: {'yes' if executed else 'no'}",
        f"- success: {'yes' if created else 'no'}",
    ]
    objects = result.metadata.get("objects") or []
    if objects:
        lines.append("- objects: " + ", ".join(objects))
    if result.artifacts:
        lines.append("- output: " + result.artifacts[0])
    if not created:
        lines.append("- note: No Blender scene was created.")
    if result.error:
        lines.append(f"- error: {result.error}")
    return "\n".join(lines).strip()
